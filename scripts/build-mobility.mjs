// Builds src/data/mobility.ts and assets/mobility/* from free-exercise-db (public domain).
// Usage: node scripts/build-mobility.mjs <path-to-exercises.json>
import fs from 'node:fs';
import path from 'node:path';

const RAW = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';
const root = path.resolve(import.meta.dirname, '..');
const byId = Object.fromEntries(JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).map((e) => [e.id, e]));

// [db id, name, region, seconds, each side?, kind]  kind: s = static stretch, d = dynamic drill
const M = [
  ['Arm_Circles', 'Arm Circles', 'upper', 30, false, 'd'],
  ['Standing_Hip_Circles', 'Hip Circles', 'lower', 30, true, 'd'],
  ['Cat_Stretch', 'Cat-Cow', 'spine', 45, false, 'd'],
  ['Worlds_Greatest_Stretch', "World's Greatest Stretch", 'lower', 40, true, 'd'],
  ['Inchworm', 'Inchworm', 'spine', 40, false, 'd'],
  ['Chest_And_Front_Of_Shoulder_Stretch', 'Chest & Front Shoulder Stretch', 'upper', 40, false, 's'],
  ['Shoulder_Stretch', 'Cross-Body Shoulder Stretch', 'upper', 30, true, 's'],
  ['Overhead_Lat', 'Overhead Lat Stretch', 'upper', 30, true, 's'],
  ['Triceps_Stretch', 'Triceps Stretch', 'upper', 30, true, 's'],
  ['Upper_Back_Stretch', 'Upper Back Stretch', 'upper', 40, false, 's'],
  ['Side_Neck_Stretch', 'Side Neck Stretch', 'upper', 25, true, 's'],
  ['Kneeling_Hip_Flexor', 'Kneeling Hip Flexor Stretch', 'lower', 40, true, 's'],
  ['Seated_Floor_Hamstring_Stretch', 'Seated Hamstring Stretch', 'lower', 45, false, 's'],
  ['Lying_Glute', 'Lying Glute Stretch', 'lower', 40, true, 's'],
  ['Quad_Stretch', 'Quad Stretch', 'lower', 30, true, 's'],
  ['Standing_Gastrocnemius_Calf_Stretch', 'Calf Stretch', 'lower', 30, true, 's'],
  ['Groin_and_Back_Stretch', 'Groin & Back Stretch', 'lower', 45, false, 's'],
  ['Knee_Across_The_Body', 'Lying Spinal Twist', 'spine', 35, true, 's'],
  ['Childs_Pose', "Child's Pose", 'spine', 60, false, 's'],
  ['Hug_Knees_To_Chest', 'Knees to Chest', 'spine', 45, false, 's'],
];

const dir = path.join(root, 'assets/mobility');
fs.mkdirSync(dir, { recursive: true });
const out = [], req = [];
for (const [id, name, region, seconds, sides, kind] of M) {
  const e = byId[id];
  if (!e) throw new Error('Missing in source db: ' + id);
  const key = id.replace(/[^A-Za-z0-9]/g, '_').toLowerCase();
  for (let i = 0; i < 2; i++) {
    const file = path.join(dir, `${key}_${i}.jpg`);
    if (!fs.existsSync(file)) {
      const res = await fetch(RAW + e.images[Math.min(i, e.images.length - 1)]);
      if (!res.ok) throw new Error(`Image fetch failed ${res.status}: ${id}`);
      fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
    }
  }
  req.push(`  ${JSON.stringify(key)}: [require('../../assets/mobility/${key}_0.jpg'), require('../../assets/mobility/${key}_1.jpg')],`);
  out.push({ id: key, name, region, seconds, sides, dynamic: kind === 'd', instructions: e.instructions });
}
fs.writeFileSync(
  path.join(root, 'src/data/mobility.ts'),
  `// GENERATED by scripts/build-mobility.mjs. Do not edit by hand.
// Drill data and images: free-exercise-db (public domain, Unlicense).
export interface Drill {
  id: string;
  name: string;
  region: 'upper' | 'lower' | 'spine';
  seconds: number;
  sides: boolean;
  dynamic: boolean;
  instructions: string[];
}

export const DRILLS: Drill[] = ${JSON.stringify(out, null, 1)};

export const DRILL_IMAGES: Record<string, [number, number]> = {
${req.join('\n')}
};
`
);
console.log(`Wrote ${out.length} drills`);
